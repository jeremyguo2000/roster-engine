"""Contract test: the MCP server and the in-app chat must expose the same tools.

`app.tooling.params` is the single source of truth for tool names, descriptions, and
parameter shapes. The chat surface derives its JSON Schema from those Pydantic models
directly, but the MCP server restates them as typed function signatures (FastMCP nests
a model-typed parameter under a `$ref`, which would change its wire shape).

That restatement is the one place the two surfaces can drift, so it's checked here: a
parameter added, renamed, or re-described on one surface and not the other fails this
test rather than silently shipping.
"""

import asyncio
import os
from typing import Any

import pytest

# The MCP server refuses to import without service-account credentials. The test only
# inspects schemas — it never logs in — so placeholders are enough.
os.environ.setdefault("ROSTER_SERVICE_USERNAME", "test")
os.environ.setdefault("ROSTER_SERVICE_PASSWORD", "test")

from app.chat.tools import ANTHROPIC_TOOLS, OPENAI_TOOLS  # noqa: E402
from app.mcp_server.server import mcp  # noqa: E402
from app.tooling.params import DESCRIPTIONS, PARAMS  # noqa: E402


def _strip_titles(node: Any) -> Any:
    """`title` is autogenerated cosmetic noise and differs by construction (Pydantic
    names it after the model, FastMCP after the function). Not part of the contract."""
    if isinstance(node, dict):
        return {k: _strip_titles(v) for k, v in node.items() if k != "title"}
    if isinstance(node, list):
        return [_strip_titles(v) for v in node]
    return node


@pytest.fixture(scope="module")
def mcp_tools() -> dict[str, Any]:
    return {t.name: t for t in asyncio.run(mcp.list_tools())}


@pytest.fixture(scope="module")
def chat_tools() -> dict[str, Any]:
    """Chat tools normalised to {name: {description, schema}} regardless of the
    provider wire shape, so the assertions below apply to both."""
    out: dict[str, Any] = {}
    for t in ANTHROPIC_TOOLS:
        out[t["name"]] = {"description": t["description"], "schema": t["input_schema"]}
    for t in OPENAI_TOOLS:
        fn = t["function"]
        # Both shapes must agree with each other as well as with MCP.
        assert out[fn["name"]]["description"] == fn["description"]
        assert out[fn["name"]]["schema"] == fn["parameters"]
    return out


def test_both_surfaces_expose_the_registry(mcp_tools, chat_tools):
    expected = set(PARAMS)
    assert set(mcp_tools) == expected, "MCP tools drifted from app.tooling.params"
    assert set(chat_tools) == expected, "chat tools drifted from app.tooling.params"
    assert {t["function"]["name"] for t in OPENAI_TOOLS} == expected


def test_openai_tools_use_the_function_wrapper():
    """The OpenAI shape must nest the schema under function.parameters — an
    endpoint like vLLM rejects Anthropic's flat input_schema form."""
    for t in OPENAI_TOOLS:
        assert t["type"] == "function"
        assert set(t["function"]) == {"name", "description", "parameters"}
        assert "input_schema" not in t["function"]


@pytest.mark.parametrize("name", sorted(PARAMS))
def test_descriptions_match(name, mcp_tools, chat_tools):
    assert mcp_tools[name].description == DESCRIPTIONS[name]
    assert chat_tools[name]["description"] == DESCRIPTIONS[name]


@pytest.mark.parametrize("name", sorted(PARAMS))
def test_parameter_schemas_match(name, mcp_tools, chat_tools):
    """The payload a model would construct must be identical on both surfaces."""
    mcp_schema = _strip_titles(mcp_tools[name].inputSchema)
    chat_schema = _strip_titles(chat_tools[name]["schema"])

    assert mcp_schema.get("properties", {}) == chat_schema.get("properties", {}), (
        f"{name}: parameter properties differ between MCP and chat"
    )
    assert sorted(mcp_schema.get("required", [])) == sorted(
        chat_schema.get("required", [])
    ), f"{name}: required parameters differ between MCP and chat"
    assert _strip_titles(mcp_schema.get("$defs", {})) == _strip_titles(
        chat_schema.get("$defs", {})
    ), f"{name}: nested definitions (e.g. DemandSpec) differ between MCP and chat"


def test_no_approve_or_discard_tool(mcp_tools, chat_tools):
    """Approving/discarding a roster is a deliberate human action in the UI. Neither
    surface should be able to do it — see the read+create-only scope decision."""
    forbidden = {"approve_roster", "discard_roster", "delete_roster"}
    assert not (forbidden & set(mcp_tools))
    assert not (forbidden & set(chat_tools))
